import polars as pl
df = pl.read_parquet('output/training_data.parquet')
print(f'Shape: {df.shape}')
print()

print('=== Class Balance ===')
print(f'timing_closure: {df["timing_closure_bin"].mean():.3f}')
print(f'drc_clean: {df["drc_clean_bin"].mean():.3f}')
print(f'lvs_clean: {df["lvs_clean_bin"].mean():.3f}')
print()

print('Platform Distribution (normalized):')
vc = df['platform'].value_counts()
print(vc / len(df))
print()

print('Key Correlations:')
print(f'WNS-TNS: {df["final_wns_ns"].corr(df["final_tns_ns"]):.3f}')
print(f'Instances-Area: {df["num_instances"].corr(df["final_area_um2"]):.3f}')
print(f'Area-Power: {df["final_area_um2"].corr(df["final_power_mw"]):.3f}')
print(f'Utilization-WNS: {df["core_utilization"].corr(df["final_wns_ns"]):.3f}')
print(f'WNS-TimingClosure: {df["final_wns_ns"].corr(df["timing_closure_bin"]):.3f}')
print(f'DRC-TimingClosure: {df["final_drc_violations"].corr(df["timing_closure_bin"]):.3f}')
print()

print('Target Ranges:')
print(f'WNS: [{df["final_wns_ns"].min():.2f}, {df["final_wns_ns"].max():.2f}]')
print(f'TNS: [{df["final_tns_ns"].min():.2f}, {df["final_tns_ns"].max():.2f}]')
print(f'Area: [{df["final_area_um2"].min():.2f}, {df["final_area_um2"].max():.2f}]')
print(f'Power: [{df["final_power_mw"].min():.2f}, {df["final_power_mw"].max():.2f}]')
print(f'DRC: [{df["final_drc_violations"].min()}, {df["final_drc_violations"].max()}]')
print()

print('Logical Consistency:')
tc_check = (df['timing_closure_bin'] == (df['final_wns_ns'] >= 0)).all()
drc_check = (df['drc_clean_bin'] == (df['final_drc_violations'] == 0)).all()
print(f'Timing closure <=> WNS>=0: {tc_check}')
print(f'DRC clean <=> DRC=0: {drc_check}')
print()

print('Platform Distribution:')
print(df['platform'].value_counts())
print()
vc = df['platform'].value_counts()
print((vc / len(df)).to_pandas().to_string())
print()

print('Sample rows:')
print(df.select(['platform', 'design_name', 'final_wns_ns', 'final_tns_ns', 'final_area_um2', 'final_power_mw', 'final_drc_violations', 'timing_closure_bin', 'drc_clean_bin']).head(10).to_pandas().to_string())
